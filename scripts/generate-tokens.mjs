#!/usr/bin/env node
/**
 * Semantic token compiler; no build-time dependencies or timestamps.
 *
 * Source: src/kit/tokens.json (legacy public data + typed tokens + CSS bindings).
 * Outputs: src/kit/generated/*.css and src/kit/tokens.dtcg.json.
 * `--check` validates source and compares every output without writing.
 * `--source FILE --out-dir DIR` supports isolated consumers/tests.
 * CSS bindings retain var()/light-dark() inheritance; DTCG contains typed
 * constants and aliases rather than mislabelling CSS expressions as colors.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const aliasPattern = /^\{([^{}]+)\}$/;
const referencePattern = /\{([^{}]+)\}/g;
const colorPattern = /^#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
const generatedHeader =
  '/* Generated by scripts/generate-tokens.mjs from tokens.json. Do not edit. */\n';
const requiredCSSFiles = [
  'base-tokens.css',
  'component-tokens.css',
  'native-shadow-tokens.css',
  'landing-tokens.css',
];

function fail(message) {
  throw new Error(message);
}
function dimension(value, path) {
  if (!value || !Number.isFinite(value.value) || !['px', 'rem'].includes(value.unit))
    fail(`Invalid dimension at ${path}`);
  return `${value.value}${value.unit}`;
}
function colorObject(value, path) {
  if (typeof value === 'string' && colorPattern.test(value)) {
    let hex = value.slice(1);
    if (hex.length < 5) hex = [...hex].map((c) => c + c).join('');
    const channels = [0, 2, 4].map(
      (offset) => Number.parseInt(hex.slice(offset, offset + 2), 16) / 255,
    );
    return {
      colorSpace: 'srgb',
      components: channels,
      alpha: hex.length === 8 ? Number.parseInt(hex.slice(6), 16) / 255 : 1,
    };
  }
  if (
    !value ||
    value.colorSpace !== 'srgb' ||
    !Array.isArray(value.components) ||
    value.components.length !== 3 ||
    value.components.some((v) => !Number.isFinite(v) || v < 0 || v > 1) ||
    (value.alpha !== undefined &&
      (!Number.isFinite(value.alpha) || value.alpha < 0 || value.alpha > 1))
  )
    fail(`Invalid sRGB color at ${path}`);
  return value;
}
function cssColor(value, path) {
  if (typeof value === 'string' && colorPattern.test(value)) return value;
  const color = colorObject(value, path);
  const channels = color.components.map((v) => Math.round(v * 255));
  return color.alpha === undefined || color.alpha === 1
    ? `rgb(${channels.join(',')})`
    : `rgba(${channels.join(',')},${color.alpha})`;
}
function cssShadow(value, path) {
  const values = Array.isArray(value) ? value : [value];
  if (!values.length) fail(`Empty shadow at ${path}`);
  return values
    .map((shadow) => {
      if (!shadow || typeof shadow !== 'object') fail(`Invalid shadow at ${path}`);
      const lengths = ['offsetX', 'offsetY', 'blur', 'spread'].map((key) =>
        dimension(shadow[key], `${path}.${key}`),
      );
      if (shadow.blur.value < 0) fail(`Negative shadow blur at ${path}`);
      if (shadow.inset !== undefined && typeof shadow.inset !== 'boolean')
        fail(`Invalid inset at ${path}`);
      return `${shadow.inset ? 'inset ' : ''}${lengths.join(' ')} ${cssColor(shadow.color, `${path}.color`)}`;
    })
    .join(',');
}

export function compileTokens(source) {
  if (!source || typeof source !== 'object' || !source.meta?.version || !source.css?.files)
    fail('Expected versioned token source and css.files bindings');
  for (const filename of requiredCSSFiles)
    if (!Array.isArray(source.css.files[filename]) || !source.css.files[filename].length)
      fail(`Missing CSS output ${filename}; stylesheet entrypoints depend on it`);
  const tokens = new Map();
  function collect(node, path = []) {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return;
    if (Object.hasOwn(node, '$value')) {
      if (!node.$type) fail(`Missing token type at ${path.join('.')}`);
      tokens.set(path.join('.'), node);
      return;
    }
    for (const [name, value] of Object.entries(node)) {
      if (name.startsWith('$') || (!path.length && (name === 'css' || name === 'meta'))) continue;
      if (/[.{}]/.test(name)) fail(`Invalid token name ${[...path, name].join('.')}`);
      collect(value, [...path, name]);
    }
  }
  collect(source);
  function resolveToken(path, trail = []) {
    if (trail.includes(path)) fail(`Circular token alias: ${[...trail, path].join(' -> ')}`);
    const token = tokens.get(path);
    if (!token) fail(`Unknown token reference ${path}`);
    const alias = typeof token.$value === 'string' && aliasPattern.exec(token.$value);
    if (!alias) return token;
    const resolved = resolveToken(alias[1], [...trail, path]);
    if (resolved.$type !== token.$type) fail(`Alias type mismatch at ${path}`);
    return { ...token, $value: resolved.$value };
  }
  function serialize(token, path) {
    const value = token.$value;
    switch (token.$type) {
      case 'color':
        return cssColor(value, path);
      case 'dimension':
        return dimension(value, path);
      case 'fontFamily': {
        const families = Array.isArray(value) ? value : [value];
        if (
          !families.length ||
          families.some((v) => typeof v !== 'string' || !v || /[;{}\n\r]/.test(v))
        )
          fail(`Invalid font family at ${path}`);
        return families
          .map((v) =>
            /^[a-zA-Z_-][a-zA-Z0-9_-]*$/.test(v)
              ? v
              : `'${v.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`,
          )
          .join(',');
      }
      case 'shadow':
        return cssShadow(value, path);
      case 'number':
      case 'fontWeight':
        if (!Number.isFinite(value)) fail(`Invalid numeric token at ${path}`);
        return String(value);
      default:
        return fail(`Unsupported token type ${token.$type} at ${path}`);
    }
  }
  // Validate every token, including tokens not currently bound to CSS.
  for (const path of tokens.keys()) serialize(resolveToken(path), path);

  const outputs = {};
  for (const [filename, rules] of Object.entries(source.css.files)) {
    if (!/^[a-z][a-z-]*\.css$/.test(filename) || !Array.isArray(rules))
      fail(`Invalid CSS output ${filename}`);
    outputs[`generated/${filename}`] =
      generatedHeader +
      rules
        .map((rule) => {
          if (
            typeof rule.selector !== 'string' ||
            !rule.selector ||
            /[{};\r\n]/.test(rule.selector) ||
            !Array.isArray(rule.declarations)
          )
            fail(`Invalid CSS rule in ${filename}`);
          return `${rule.selector}{\n${rule.declarations
            .map((declaration) => {
              if (!Array.isArray(declaration) || declaration.length !== 2)
                fail(`Invalid declaration in ${filename}`);
              const [property, expression] = declaration;
              if (!/^--[a-zA-Z][\w-]*$/.test(property) && property !== 'color-scheme')
                fail(`Invalid CSS property ${property}`);
              if (typeof expression !== 'string' || /[;\r\n]/.test(expression))
                fail(`Invalid CSS binding for ${property}`);
              const value = expression.replace(referencePattern, (_, path) =>
                serialize(resolveToken(path), path),
              );
              if (/[{}]/.test(value)) fail(`Malformed CSS reference for ${property}`);
              return `  ${property}:${value};`;
            })
            .join('\n')}\n}\n`;
        })
        .join('');
  }

  // Export only DTCG tokens/groups. Legacy measurements, CSS recipes and
  // provenance stay in tokens.json and the immutable official source JSONs.
  const dtcg = {
    $description:
      'mDesign typed tokens. Generated from tokens.json; CSS context bindings and source provenance are published separately.',
  };
  for (const [path, token] of tokens) {
    const exported = { $type: token.$type, $value: token.$value };
    if (token.$description) exported.$description = token.$description;
    const alias = typeof token.$value === 'string' && aliasPattern.test(token.$value);
    if (!alias && token.$type === 'color') exported.$value = colorObject(token.$value, path);
    if (!alias && token.$type === 'shadow') {
      const convertShadow = (shadow) => ({ ...shadow, color: colorObject(shadow.color, path) });
      exported.$value = Array.isArray(token.$value)
        ? token.$value.map(convertShadow)
        : convertShadow(token.$value);
    }
    const parts = path.split('.');
    let group = dtcg;
    for (const part of parts.slice(0, -1)) group = group[part] ??= {};
    group[parts.at(-1)] = exported;
  }
  outputs['tokens.dtcg.json'] = JSON.stringify(dtcg, null, 2) + '\n';
  return {
    outputs,
    tokenCount: tokens.size,
    declarationCount: Object.values(source.css.files)
      .flat()
      .reduce((sum, rule) => sum + rule.declarations.length, 0),
  };
}

export async function generateTokens({
  sourcePath = resolve(projectRoot, 'src/kit/tokens.json'),
  outputDirectory = resolve(projectRoot, 'src/kit'),
  check = false,
} = {}) {
  const source = JSON.parse(await readFile(sourcePath, 'utf8'));
  const { outputs, tokenCount, declarationCount } = compileTokens(source);
  const drift = [];
  for (const [relativePath, contents] of Object.entries(outputs)) {
    const path = resolve(outputDirectory, relativePath);
    let actual;
    try {
      actual = await readFile(path, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (actual === contents) continue;
    drift.push(relativePath);
    if (!check) {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, contents);
    }
  }
  return { check, drift, files: Object.keys(outputs), tokenCount, declarationCount };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const options = {};
    for (let i = 2; i < process.argv.length; i++) {
      const arg = process.argv[i];
      if (arg === '--check') options.check = true;
      else if (arg === '--source' || arg === '--out-dir') {
        const value = process.argv[++i];
        if (!value || value.startsWith('--')) fail(`Missing value for ${arg}`);
        options[arg === '--source' ? 'sourcePath' : 'outputDirectory'] = resolve(value);
      } else fail(`Unknown argument ${arg}`);
    }
    const result = await generateTokens(options);
    if (result.check && result.drift.length) {
      console.error(
        `Token output drift: ${result.drift.join(', ')}. Run node scripts/generate-tokens.mjs.`,
      );
      process.exitCode = 1;
    } else
      console.log(
        `${result.check ? 'Checked' : 'Generated'} ${result.files.length} token files; ${result.tokenCount} typed tokens, ${result.declarationCount} CSS declarations.`,
      );
  } catch (error) {
    console.error(`Token generation failed: ${error.message}`);
    process.exitCode = 1;
  }
}
